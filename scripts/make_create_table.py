"""
Write a Python script that creates the k3_fq_isog table in an LMFDB
database, with the column types, table description and column descriptions
taken from schemas/k3_fq_isog.md.

    python3 scripts/make_create_table.py > test_upload/create_k3_fq_isog.py

Run the output from an LMFDB checkout with write access to the database.
"""
import os
import re
import sys
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMA = os.path.join(ROOT, "schemas", "k3_fq_isog.md")

TABLE_DESCRIPTION = (
    "Motives of K3 type over finite fields, up to isogeny.  Each row is a "
    "polynomial P(T) = q + a_1 T + ... + a_22 T^22 in Z[T] with a_22 = +-q and "
    "all roots on the unit circle; for a K3 surface X over F_q, "
    "P(T) = q det(1 - q^{-1} Frob T | H^2(X))."
)


def schema_columns():
    cols = []
    with open(SCHEMA) as F:
        for line in F:
            m = re.match(r"^\| ([a-z0-9_]+) \| ([a-z0-9 \[\]]+) \| (.*) \|\s*$", line)
            if m and m.group(1) != "Column":
                cols.append((m.group(1), m.group(2).strip(), m.group(3).strip()))
    return cols


def main():
    sys.path.insert(0, ROOT)
    from k3fq.columns import ISOG_COLUMNS
    cols = schema_columns()
    assert [(c, t) for c, t, _ in cols] == ISOG_COLUMNS, "schema and k3fq/columns.py disagree"
    by_type = OrderedDict()
    for col, typ, _ in cols:
        by_type.setdefault(typ, []).append(col)
    out = []
    out.append("# Generated by scripts/make_create_table.py from schemas/k3_fq_isog.md; do not edit by hand.")
    out.append("from lmfdb import db")
    out.append("")
    out.append("search_columns = {")
    for typ, names in by_type.items():
        out.append("    %r: %r," % (typ, names))
    out.append("}")
    out.append("")
    out.append("col_description = {")
    for col, _, desc in cols:
        out.append("    %r: %r," % (col, desc))
    out.append("}")
    out.append("")
    out.append("db.create_table(")
    out.append('    "k3_fq_isog",')
    out.append("    search_columns,")
    out.append('    label_col="label",')
    out.append("    table_description=%r," % TABLE_DESCRIPTION)
    out.append("    col_description=col_description,")
    out.append('    sort=["q", "poly"],')
    out.append("    force_description=True,")
    out.append(")")
    print("\n".join(out))


if __name__ == "__main__":
    main()
